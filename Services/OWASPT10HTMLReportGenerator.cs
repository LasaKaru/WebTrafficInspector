            html.AppendLine("<head>");
            html.AppendLine("    <meta charset='UTF-8'>");
            html.AppendLine("    <meta name='viewport' content='width=device-width, initial-scale=1.0'>");
            html.AppendLine("    <title>OWASP Top 10 2025 - Security Scan Report</title>");
            html.AppendLine("    <style>");
            html.AppendLine(GetCSS());
            html.AppendLine("    </style>");
            html.AppendLine("</head>");
            html.AppendLine("<body>");

            // Header
            html.AppendLine("<div class='header'>");
            html.AppendLine("    <h1>🛡️ OWASP Top 10 2025 Security Scan Report</h1>");
            html.AppendLine($"    <p>Generated: {DateTime.Now:yyyy-MM-dd HH:mm:ss}</p>");
            html.AppendLine($"    <p>Total URLs Scanned: {scanResults.Count}</p>");
            html.AppendLine("</div>");

            // Executive Summary
            html.AppendLine(GenerateExecutiveSummary(scanResults));

            // Vulnerability Summary by Category
            html.AppendLine(GenerateVulnerabilitySummary(scanResults));

            // Detailed Scan Results
            foreach (var scanResult in scanResults)
            {
                html.AppendLine(GenerateDetailedScanResult(scanResult.Key, scanResult.Value));
            }

            // Footer
            html.AppendLine("<div class='footer'>");
            html.AppendLine("    <p>Report generated by Web Traffic Inspector - OWASP Top 10 2025 Scanner</p>");
            html.AppendLine($"    <p>© {DateTime.Now.Year} - All vulnerabilities should be remediated as soon as possible</p>");
            html.AppendLine("</div>");

            html.AppendLine("</body>");
            html.AppendLine("</html>");

            return html.ToString();
        }

